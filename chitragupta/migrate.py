"""Forward-only, idempotent migration of an existing data home's runtime files to Chitragupta's names.

    python -m chitragupta migrate [--dry-run]

Migration "database-mcp-rename":
  - config.json  mcp.<legacy>  -> mcp.database (every sub-key kept). When `label` is absent it is derived from the
    old `server` value (split on "-", capitalise each part, join with "-"), so rendered headings keep their text.
  - health.json  under "mcp": keys <legacy> -> database and <legacy>-* -> database-* (skip, last_skip_reason, jobs,
    offline, ...), and the job names recorded in mcp.denied.
  - config.json  chitragupta_migrations += ["database-mcp-rename"], so it runs once.
Migration "branch-tracking" (v0.2.0, data/meta.json schema_version -> 4):
  - data/branches.json (one file, all repos) -> data/git/<repo>/branches.json, keeping what the reflog may no longer
    know (parent, fork, created time, first seen). The old file stays as it was; nothing writes it any more.
  - data/git/<repo>/events.jsonl seeded from today's reflogs of every watched repo (read-only git), so the history
    outlives git's reflog expiry.
  - config.json gains "branching" (guard_mode warn, stale_pr_days 3, repos {}); `branch_fetch` is retired.
Changed files are copied to <home>/.worklog/backups/chitragupta-migrate-<timestamp>/ before anything is changed.
Per-job MCP cache files (.worklog/cache/mcp/) are regenerated by the next job and are left alone.
A real run takes the agent lock (waits up to 5 minutes for a running tick, else reports "skipped" and changes nothing);
the tick runs pending migrations itself (it already holds the lock).
"""
import json
import os
import shutil
import sys
import time

from . import common

MIGRATION_ID = "database-mcp-rename"
BRANCH_ID = "branch-tracking"
SCHEMA_VERSION = 4
MIGRATIONS = (MIGRATION_ID, BRANCH_ID)
NEW = "database"
# legacy key from the original worklog engine (built at runtime: the old name is not written out in the source)
LEGACY = "d" + "pilot"


def _label(server):
    return "-".join(p[:1].upper() + p[1:] for p in str(server).split("-"))


def _rename_key(key):
    if key == LEGACY:
        return NEW
    if isinstance(key, str) and key.startswith(LEGACY + "-"):
        return NEW + key[len(LEGACY):]
    return key


def migrate_config(cfg, notes):
    """In place. Returns True if anything changed (the marker excluded)."""
    mcp = cfg.get("mcp")
    if not isinstance(mcp, dict) or LEGACY not in mcp:
        return False
    old = mcp.pop(LEGACY)
    old = old if isinstance(old, dict) else {}
    new = mcp.get(NEW) if isinstance(mcp.get(NEW), dict) else {}
    merged = dict(old)
    merged.update(new)  # a value already under the new key wins
    if not merged.get("label") and old.get("server"):
        merged["label"] = _label(old["server"])
        notes.append("config: mcp.%s.label derived from the old server name" % NEW)
    mcp[NEW] = merged
    notes.append("config: mcp.<legacy> -> mcp.%s (%d keys)" % (NEW, len(merged)))
    return True


def migrate_health(health, notes):
    """In place. Returns True if anything changed."""
    m = health.get("mcp")
    if not isinstance(m, dict):
        return False
    changed = False
    for name, val in list(m.items()):
        if isinstance(val, dict):
            for k in list(val):
                nk = _rename_key(k)
                if nk != k:
                    v = val.pop(k)
                    if nk not in val:
                        val[nk] = v
                    notes.append("health: mcp.%s.<legacy>%s -> %s" % (name, k[len(LEGACY):], nk))
                    changed = True
        elif name == "denied" and isinstance(val, list):
            n = 0
            for rec in val:
                if isinstance(rec, dict) and _rename_key(rec.get("job")) != rec.get("job"):
                    rec["job"] = _rename_key(rec["job"])
                    n += 1
            if n:
                changed = True
                notes.append("health: %d job name(s) in mcp.denied renamed" % n)
    return changed


def migrate_branches(cfg, notes, dry_run):
    """data/branches.json -> data/git/<repo>/branches.json, reflogs -> events.jsonl, config "branching", schema 4."""
    from . import gittrack
    legacy = common.read_json(common.hp("data", "branches.json"), None) or {}
    keep = ("parent", "parent_ref", "parent_source", "fork_sha", "created_at", "created_source", "first_seen",
            "deleted_at", "ticket", "local_since", "parent_alternatives")
    for repo, recs in sorted(legacy.items()):
        if not isinstance(recs, dict):
            continue
        name = gittrack.repo_key(repo)
        if os.path.exists(gittrack.gdir(name, "branches.json")):
            continue
        out = {}
        for b, r in recs.items():
            if not isinstance(r, dict) or gittrack.ignored(cfg, r.get("ticket")):
                continue
            n = {k: r[k] for k in keep if r.get(k) is not None}
            if n.get("parent_source") == "reflog (HEAD)":
                n["parent_source"] = "reflog"
            if n.get("ticket"):
                n["link"] = {"how": "branch name"}
            n.update(branch=b, repo_name=name, v=2)
            out[b] = n
        notes.append("data/git/%s/branches.json: %d branch record(s) kept from data/branches.json" % (name, len(out)))
        if not dry_run:
            common.write_json(gittrack.gdir(name, "branches.json"), out)
    for path in cfg.get("watched_repos") or []:
        if not os.path.exists(os.path.join(path, ".git")):
            continue
        name = gittrack.repo_key(path)
        if dry_run:
            notes.append("data/git/%s/events.jsonl: seed from the reflogs" % name)
            continue
        try:
            r = gittrack.Repo(cfg, path)
            tr = gittrack.Tracker(cfg, {}, None)
            tr.read_reflogs(r)
            r.data.save()
            n = len(r.data.events())
            notes.append("data/git/%s/events.jsonl: %d event(s) from the reflogs" % (name, n))
        except Exception as e:  # noqa: BLE001 - a repo that can't be read is seeded by the next tick
            notes.append("data/git/%s: reflogs not read (%s); the tick will try again" % (name, str(e)[:120]))
    if not isinstance(cfg.get("branching"), dict):
        cfg["branching"] = {"guard_mode": "warn", "stale_pr_days": 3, "repos": {}}
        notes.append('config: "branching" added (guard_mode warn, stale_pr_days 3, no repo strategies yet)')
    if "branch_fetch" in cfg:
        notes.append("config: branch_fetch is retired (branch tracking fetches without pruning: branching.fetch)")
    meta_p = common.hp("data", "meta.json")
    meta = common.read_json(meta_p, None) or {}
    if int(meta.get("schema_version") or 1) < SCHEMA_VERSION:
        notes.append("data/meta.json: schema_version %s -> %d" % (meta.get("schema_version", 1), SCHEMA_VERSION))
        if not dry_run:
            meta["schema_version"] = SCHEMA_VERSION
            meta["upgraded_branch_tracking"] = common.now_iso()
            common.write_json(meta_p, meta)
    return True


def _backup(paths):
    dest = common.wl("backups", "chitragupta-migrate-" + time.strftime("%Y%m%d-%H%M%S"))
    n, base = 2, dest
    while os.path.exists(dest):
        dest, n = "%s-%d" % (base, n), n + 1
    os.makedirs(dest)
    for p in paths:
        if os.path.isfile(p):
            shutil.copy2(p, os.path.join(dest, os.path.basename(p)))
    return dest


def run(dry_run=False, wait_s=None):
    if dry_run:
        return _run(True)
    from .agent import Lock
    lock = Lock()
    if not lock.acquire_wait(wait_s):
        return {"home": common.home(), "dry_run": False, "changes": [], "backup": None, "already": False,
                "skipped": "the agent is busy (a tick holds the lock); run migrate again in a few minutes"}
    try:
        return _run(False)
    finally:
        lock.release()


def _run(dry_run):
    cpath, hpath = common.wl("config.json"), common.wl("health.json")
    out = {"home": common.home(), "dry_run": dry_run, "changes": [], "backup": None, "already": False}
    if not os.path.isfile(cpath):
        out["changes"].append("no config.json: nothing to migrate")
        return out
    try:
        with open(cpath, encoding="utf-8") as f:
            cfg = json.load(f)
    except (OSError, ValueError) as e:
        out["error"] = "config.json unreadable: %s" % e
        return out
    done = list(cfg.get("chitragupta_migrations") or [])
    pending = [m for m in MIGRATIONS if m not in done]
    if not pending:
        out["already"] = True
        return out
    health = common.read_json(hpath, {}) or {}
    notes = []
    cfg_changed = health_changed = False
    if not dry_run:
        out["backup"] = _backup([cpath, hpath, common.hp("data", "meta.json"), common.hp("data", "branches.json")])
    if MIGRATION_ID in pending:
        cfg_changed = migrate_config(cfg, notes)
        health_changed = migrate_health(health, notes) if isinstance(health, dict) else False
        if not notes:
            notes.append("nothing to rename; recording the migration marker")
    if BRANCH_ID in pending:
        migrate_branches(cfg, notes, dry_run)
        cfg_changed = True
    cfg["chitragupta_migrations"] = done + pending
    out["changes"] = notes
    out["applied"] = pending
    if dry_run:
        return out
    common.write_json(cpath, cfg)
    if health_changed:
        common.write_json(hpath, health)
    out["config_changed"], out["health_changed"] = cfg_changed, health_changed
    return out


def run_in_tick():
    """Pending migrations from inside the tick (which holds the agent lock). None when there is nothing to do."""
    cfg = common.read_json(common.wl("config.json"), None)
    if not isinstance(cfg, dict) or all(m in (cfg.get("chitragupta_migrations") or []) for m in MIGRATIONS):
        return None
    res = _run(False)
    common.log("agent", "migrations: %s" % json.dumps({k: res.get(k) for k in ("applied", "backup", "error")}))
    return res


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if any(a in ("-h", "--help") for a in argv):
        print(__doc__)
        return 0
    res = run(dry_run="--dry-run" in argv)
    print(json.dumps(res, indent=1))
    return 1 if res.get("error") else (3 if res.get("skipped") else 0)


if __name__ == "__main__":
    sys.exit(main())
