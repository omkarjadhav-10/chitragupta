"""Forward-only, idempotent migration of an existing data home's runtime files to Chitragupta's names.

    python -m chitragupta migrate [--dry-run]

Migration "database-mcp-rename":
  - config.json  mcp.<legacy>  -> mcp.database (every sub-key kept). When `label` is absent it is derived from the
    old `server` value (split on "-", capitalise each part, join with "-"), so rendered headings keep their text.
  - health.json  under "mcp": keys <legacy> -> database and <legacy>-* -> database-* (skip, last_skip_reason, jobs,
    offline, ...), and the job names recorded in mcp.denied.
  - config.json  chitragupta_migrations += ["database-mcp-rename"], so it runs once.
Both files are copied to <home>/.worklog/backups/chitragupta-migrate-<timestamp>/ before anything is changed.
Per-job MCP cache files (.worklog/cache/mcp/) are regenerated by the next job and are left alone.
"""
import json
import os
import shutil
import sys
import time

from . import common

MIGRATION_ID = "database-mcp-rename"
NEW = "database"
# legacy key from the original worklog engine (built at runtime: the old name is not written out in the source)
LEGACY = "d" + "pilot"


def _label(server):
    return "-".join(p[:1].upper() + p[1:] for p in str(server).split("-"))


def _rename_key(key):
    if key == LEGACY:
        return NEW
    if isinstance(key, str) and key.startswith(LEGACY + "-"):
        return NEW + key[len(LEGACY):]
    return key


def migrate_config(cfg, notes):
    """In place. Returns True if anything changed (the marker excluded)."""
    mcp = cfg.get("mcp")
    if not isinstance(mcp, dict) or LEGACY not in mcp:
        return False
    old = mcp.pop(LEGACY)
    old = old if isinstance(old, dict) else {}
    new = mcp.get(NEW) if isinstance(mcp.get(NEW), dict) else {}
    merged = dict(old)
    merged.update(new)  # a value already under the new key wins
    if not merged.get("label") and old.get("server"):
        merged["label"] = _label(old["server"])
        notes.append("config: mcp.%s.label derived from the old server name" % NEW)
    mcp[NEW] = merged
    notes.append("config: mcp.<legacy> -> mcp.%s (%d keys)" % (NEW, len(merged)))
    return True


def migrate_health(health, notes):
    """In place. Returns True if anything changed."""
    m = health.get("mcp")
    if not isinstance(m, dict):
        return False
    changed = False
    for name, val in list(m.items()):
        if isinstance(val, dict):
            for k in list(val):
                nk = _rename_key(k)
                if nk != k:
                    v = val.pop(k)
                    if nk not in val:
                        val[nk] = v
                    notes.append("health: mcp.%s.<legacy>%s -> %s" % (name, k[len(LEGACY):], nk))
                    changed = True
        elif name == "denied" and isinstance(val, list):
            n = 0
            for rec in val:
                if isinstance(rec, dict) and _rename_key(rec.get("job")) != rec.get("job"):
                    rec["job"] = _rename_key(rec["job"])
                    n += 1
            if n:
                changed = True
                notes.append("health: %d job name(s) in mcp.denied renamed" % n)
    return changed


def _backup(paths):
    dest = common.wl("backups", "chitragupta-migrate-" + time.strftime("%Y%m%d-%H%M%S"))
    n, base = 2, dest
    while os.path.exists(dest):
        dest, n = "%s-%d" % (base, n), n + 1
    os.makedirs(dest)
    for p in paths:
        if os.path.isfile(p):
            shutil.copy2(p, os.path.join(dest, os.path.basename(p)))
    return dest


def run(dry_run=False):
    cpath, hpath = common.wl("config.json"), common.wl("health.json")
    out = {"home": common.home(), "dry_run": dry_run, "changes": [], "backup": None, "already": False}
    if not os.path.isfile(cpath):
        out["changes"].append("no config.json: nothing to migrate")
        return out
    try:
        with open(cpath, encoding="utf-8") as f:
            cfg = json.load(f)
    except (OSError, ValueError) as e:
        out["error"] = "config.json unreadable: %s" % e
        return out
    done = cfg.get("chitragupta_migrations") or []
    if MIGRATION_ID in done:
        out["already"] = True
        return out
    health = common.read_json(hpath, {}) or {}
    notes = []
    cfg_changed = migrate_config(cfg, notes)
    health_changed = migrate_health(health, notes) if isinstance(health, dict) else False
    cfg["chitragupta_migrations"] = list(done) + [MIGRATION_ID]
    out["changes"] = notes or ["nothing to rename; recording the migration marker"]
    if dry_run:
        return out
    out["backup"] = _backup([cpath, hpath])
    common.write_json(cpath, cfg)
    if health_changed:
        common.write_json(hpath, health)
    out["config_changed"], out["health_changed"] = cfg_changed, health_changed
    return out


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if any(a in ("-h", "--help") for a in argv):
        print(__doc__)
        return 0
    res = run(dry_run="--dry-run" in argv)
    print(json.dumps(res, indent=1))
    return 1 if res.get("error") else 0


if __name__ == "__main__":
    sys.exit(main())
