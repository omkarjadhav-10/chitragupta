def at(day, hh, mm):
    return dt.datetime.combine(dt.date.fromisoformat(day), dt.time(hh, mm)).astimezone()


def base_config(**over):
    cfg = {"ticket_prefixes": ["ABC"], "day_starts_at": "07:00", "github_remote": "",
           "capture_scope": {"include_paths": [], "exclude_paths": []}, "paths": {"python": PY},
           "git_author_emails": [], "watched_repos": [], "bruno_collections": [],
           "artifacts": {"watch_dirs": [], "push_binary_types": []}}
    cfg.update(over)
    return cfg


class Case(Isolated, unittest.TestCase):
    config = base_config()

    def setUp(self):
        home = tempfile.mkdtemp(prefix="cg-v010-")
        write_config(home, json.loads(json.dumps(self.config)))
        self.isolate(home)
        from chitragupta import agent, common, extract, jiraworklog, slack
        self._saved = (extract.call_claude, slack.send, jiraworklog.slack.send, common.now, agent.LOCK_WAIT_S)
        self.calls, self.sent = [], []

        def fake_call(kind, stdin_text, cfg, timeout=300):
            self.calls.append(kind)
            return {"descriptions": []}, 0.0

        def fake_send(cfg, text, health):
            self.sent.append(text)
            return {"ok": True, "ts": "1760000000.000100"}
        extract.call_claude = fake_call
        slack.send = jiraworklog.slack.send = fake_send
        agent.LOCK_WAIT_S = 0

    def tearDown(self):
        from chitragupta import agent, common, extract, jiraworklog, slack
        extract.call_claude, slack.send, jiraworklog.slack.send, common.now, agent.LOCK_WAIT_S = self._saved
        for lk in getattr(self, "_held", []):
            lk.release()
        self.restore()

    def clock(self, day, hh, mm):
        from chitragupta import common
        t = at(day, hh, mm)
        common.now = lambda: t
        return t

    def raw(self, day, ticket, hh, mm, n=20, step=5, sid="s1", branch=None):
        from chitragupta import common
        p = common.wl("raw", day, sid + ".jsonl")
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "a", encoding="utf-8") as f:
            t = at(day, hh, mm)
            for i in range(n):
                f.write(json.dumps({"ts": (t + dt.timedelta(minutes=i * step)).isoformat(), "event": "post-tool",
                                    "session_id": sid, "branch": branch or "feature/%s-x" % ticket, "payload": {}}) + "\n")

    def agent(self):
        from chitragupta import agent
        a = agent.Agent()
        # load_config() shares nested default dicts: copy before a test changes a.cfg
        a.cfg = a.jwl.cfg = a.jobs.cfg = json.loads(json.dumps(a.cfg))
        a.health.setdefault("jira_worklog", {})["active_from"] = "2026-10-14"
        return a

    def hold_agent_lock(self):
        from chitragupta import agent
        lk = agent.Lock()
        self.assertTrue(lk.acquire())
        self._held = getattr(self, "_held", []) + [lk]  # released in tearDown, while the temp home is still current
        return lk


