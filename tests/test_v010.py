class LockTests(Case):
    def test_worklog_show_jira_waits_for_lock(self):
        from chitragupta import agent
        self.clock("2026-10-16", 12, 0)
        self.hold_agent_lock()
        out = io.StringIO()
        with redirect_stdout(out):
            rc = agent.main(["worklog-show", "--jira"])
        self.assertEqual(rc, 1)
        self.assertIn("agent busy", out.getvalue())
        out = io.StringIO()
        with redirect_stdout(out):  # the plain preview is read-only: no lock needed
            self.assertEqual(agent.main(["worklog-show"]), 0)

    def test_worklog_show_jira_releases_lock(self):
        from chitragupta import agent, common
        self.clock("2026-10-16", 12, 0)
        with redirect_stdout(io.StringIO()):
            self.assertEqual(agent.main(["worklog-show", "--jira"]), 0)
        self.assertFalse(os.path.exists(common.wl("locks", "agent.lock")))
        self.assertTrue(os.path.isfile(common.wl("health.json")))

    def test_acquire_wait_times_out(self):
        from chitragupta import agent
        self.hold_agent_lock()
        t0 = time.time()
        self.assertFalse(agent.Lock().acquire_wait(0.3, 0.05))
        self.assertGreaterEqual(time.time() - t0, 0.25)

    def test_loop_single_instance(self):
        from chitragupta import agent, common
        ticks, sleeps = [], []
        real = agent.cmd_tick
        agent.cmd_tick = lambda force=False: ticks.append(1) or 0
        try:
            other = agent.Lock("loop.lock")
            self.assertTrue(other.acquire())
            with redirect_stdout(io.StringIO()) as out:
                self.assertEqual(agent.cmd_loop(max_ticks=2, sleep=sleeps.append), 0)
            self.assertIn("already running", out.getvalue())
            self.assertEqual(ticks, [])
            other.release()
            self.assertEqual(agent.cmd_loop(max_ticks=2, interval=7, sleep=sleeps.append), 0)
            self.assertEqual(ticks, [1, 1])
            self.assertEqual(sleeps, [7])
            self.assertFalse(os.path.exists(common.wl("locks", "loop.lock")))
        finally:
            agent.cmd_tick = real

    def test_migrate_takes_lock(self):
        from chitragupta import common, migrate
        cpath = common.wl("config.json")
        cfg = json.loads(rd(cpath))
        cfg["mcp"] = {migrate.LEGACY: {"enabled": True, "server": "db-x"}}
        write_config(common.home(), cfg)
        before = rd(cpath)
        lk = self.hold_agent_lock()
        res = migrate.run(wait_s=0)
        self.assertIn("skipped", res)
        self.assertEqual(rd(cpath), before)
        self.assertTrue(migrate.run(dry_run=True)["changes"])  # a dry run needs no lock
        lk.release()
        res = migrate.run(wait_s=0)
        self.assertNotIn("skipped", res)
        self.assertEqual(json.loads(rd(cpath))["mcp"]["database"]["server"], "db-x")
        self.assertFalse(os.path.exists(common.wl("locks", "agent.lock")))
        self.hold_agent_lock()
        with redirect_stdout(io.StringIO()) as out:
            self.assertEqual(migrate.main([]), 3)  # busy: exit 3, "skipped" in the JSON
        self.assertIn("skipped", json.loads(out.getvalue()))


